@router.put("/caregiver-rates", response_model=dict)
def upsert_caregiver_rate(
    payload: CaregiverRateUpsert,
    _: User = Depends(require_admin_or_supervisor),
    db: Session = Depends(get_db),
):
    if payload.pay_day < 0 or payload.pay_night < 0:
        raise HTTPException(status_code=400, detail="pay_day and pay_night cannot be negative")

    caregiver_exists = db.query(Caregiver.caregiver_id).filter(Caregiver.caregiver_id == payload.caregiver_id).first()
    if not caregiver_exists:
        raise HTTPException(status_code=404, detail="Caregiver not found")
    client_exists = db.query(Client.client_id).filter(Client.client_id == payload.client_id).first()
    if not client_exists:
        raise HTTPException(status_code=404, detail="Client not found")

    row = (
        db.query(CaregiverClientRate)
        .filter(
            CaregiverClientRate.caregiver_id == payload.caregiver_id,
            CaregiverClientRate.client_id == payload.client_id,
        )
        .first()
    )
    if not row:
        row = CaregiverClientRate(
            caregiver_id=payload.caregiver_id,
            client_id=payload.client_id,
            pay_day=float(payload.pay_day),
            pay_night=float(payload.pay_night),
            is_custom=1,
        )
        db.add(row)
    else:
        row.pay_day = float(payload.pay_day)
        row.pay_night = float(payload.pay_night)
        row.is_custom = 1

    db.commit()
    db.refresh(row)

    caregiver_name = db.query(Caregiver.name).filter(Caregiver.caregiver_id == row.caregiver_id).scalar()
    client_name = db.query(Client.name).filter(Client.client_id == row.client_id).scalar()
    return {
        "rate_id": row.rate_id,
        "caregiver_id": row.caregiver_id,
        "caregiver_name": caregiver_name,
        "client_id": row.client_id,
        "client_name": client_name,
        "pay_day": float(row.pay_day or 0.0),
        "pay_night": float(row.pay_night or 0.0),
    }


