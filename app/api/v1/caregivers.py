@router.put("/caregivers/{caregiver_id}")
def update_caregiver(caregiver_id: int,
                     payload: CaregiverUpdate,
                     db: Session = Depends(get_db),
                     _: object = Depends(require_admin_or_supervisor)):

    cg = (db.query(Caregiver)
            .options(joinedload(Caregiver.user))
            .filter(Caregiver.caregiver_id == caregiver_id)
            .first())
    if not cg:
        raise HTTPException(status_code=404, detail="Caregiver not found")

    # Caregiver fields
    if payload.name is not None: cg.name = payload.name
    if payload.phone is not None: cg.phone = payload.phone
    if payload.address is not None: cg.address = payload.address
    if payload.active is not None: cg.active = payload.active

    # User fields (email/password)
    if payload.email is not None:
        # ensure email unique
        exists = db.query(User).filter(User.email == payload.email, User.user_id != cg.user_id).first()
        if exists:
            raise HTTPException(status_code=400, detail="Email already in use")
        cg.user.email = payload.email
    if payload.password:
        cg.user.password_hash = hash_password(payload.password)
        cg.user.must_change_password = 1

    db.commit()
    db.refresh(cg)

    return {
        "caregiver_id": cg.caregiver_id,
        "user_id": cg.user_id,
        "name": cg.name,
        "email": cg.user.email if cg.user else None,
        "phone": cg.phone,
        "address": cg.address,
        "active": cg.active,
    }



