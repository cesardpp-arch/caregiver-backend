@router.delete("/caregivers/{caregiver_id}", status_code=204)
def delete_caregiver(caregiver_id: int, _: User = Depends(require_admin_or_supervisor), db: Session = Depends(get_db)):
    cg = db.query(Caregiver).filter(Caregiver.caregiver_id == caregiver_id).first()
    if not cg:
        raise HTTPException(status_code=404, detail="Caregiver not found")

    from app.models.tables import Shift
    any_shifts = db.query(Shift.shift_id).filter(
        Shift.caregiver_id == caregiver_id
    ).first()
    if any_shifts:
        open_count = db.query(Shift.shift_id).filter(
            Shift.caregiver_id == caregiver_id,
            Shift.status == "OPEN"
        ).count()
        if open_count:
            raise HTTPException(
                status_code=400,
                detail=f"Cannot delete caregiver '{cg.name}' — they have {open_count} open shift(s). "
                       "Close or void those shifts first, then deactivate instead of deleting."
            )
        raise HTTPException(
            status_code=400,
            detail=f"Cannot delete caregiver '{cg.name}' — they have shift history on record. "
                   "Deactivate them instead (set Active = No) to preserve payroll records."
        )

    db.delete(cg)
    db.commit()
    return

