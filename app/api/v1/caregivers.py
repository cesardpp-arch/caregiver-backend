@router.post("/caregivers", response_model=dict)
def create_caregiver(
    payload: CaregiverCreate,
    db: Session = Depends(get_db),
    _: object = Depends(require_admin_or_supervisor),
):
    email = payload.email.strip().lower()

    # 1) Email must be unique in users
    existing_user = db.query(User).filter(User.email == email).first()
    if existing_user:
        raise HTTPException(status_code=400, detail="Email already exists")

    # 2) Choose password
    raw_password = payload.password or secrets.token_urlsafe(10)  # auto temp password
    password_hash = hash_password(raw_password)

    # 3) Create User (login)
    u = User(
        email=email,
        password_hash=password_hash,
        role="CAREGIVER",
        status="ACTIVE" if (payload.active is None or payload.active == 1) else "INACTIVE",
        must_change_password=1,
    )
    db.add(u)
    db.flush()  # get u.user_id

    # 4) Create Caregiver (profile)
    c = Caregiver(
        user_id=u.user_id,
        name=payload.name,
        phone=payload.phone,
        address=payload.address,
        active=1 if (payload.active is None or payload.active == 1) else 0,
    )
    db.add(c)
    db.flush()
    db.commit()
    db.refresh(c)

    # Return temp password ONLY if you autogenerated it
    return {
        "caregiver_id": c.caregiver_id,
        "user_id": u.user_id,
        "name": c.name,
        "email": u.email,
        "active": c.active,
        "temp_password": (raw_password if payload.password is None else None),
    }



